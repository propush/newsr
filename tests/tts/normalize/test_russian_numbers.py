from __future__ import annotations

import pytest

from newsr.tts.normalize.russian_numbers import russian_numbers_to_words


@pytest.mark.parametrize(
    ("text", "expected"),
    [
        ("раунд на 700 млн долларов", "раунд на семьсот миллионов долларов"),
        ("заказы на 1 млрд долларов", "заказы на один миллиард долларов"),
        ("рост до 40% за год", "рост до сорока процентов за год"),
        ("о росте на 40%", "о росте на сорок процентов"),
        ("до 11 пластин", "до одиннадцати пластин"),
        ("версия с 16 ГБ памяти", "версия с шестнадцатью гигабайтами памяти"),
        ("с 5 до 10 участников", "с пяти до десяти участников"),
        ("в 2 раза больше, по 3 штуки", "в два раза больше, по три штуки"),
        ("около 1,5 млрд долларов", "около одной целой пяти десятых миллиарда долларов"),
        ("на 1 тыс. рублей и 21 компанию", "на одну тысячу рублей и двадцать одну компанию"),
        ("выручка $5 млн", "выручка пять миллионов долларов"),
        ("скорость до 40 Гбит/с", "скорость до сорока гигабит в секунду"),
        ("экран 5×5 дюймов", "экран пять на пять дюймов"),
    ],
)
def test_numbers_units_and_currency_agree_with_context(text: str, expected: str) -> None:
    assert russian_numbers_to_words(text) == expected


@pytest.mark.parametrize(
    ("text", "expected"),
    [
        ("релиз в марте 2027 года", "релиз в марте две тысячи двадцать седьмого года"),
        ("В 2026 году", "В две тысячи двадцать шестом году"),
        ("к 2028 году", "к две тысячи двадцать восьмому году"),
        ("в 2020–2025 гг. выросла", "в две тысячи двадцатом — две тысячи двадцать пятом годах выросла"),
        ("в понедельник, 28 сентября", "в понедельник, двадцать восьмого сентября"),
        ("к 1 марта", "к первому марта"),
        ("с 3 по 5 октября", "с третьего по пятое октября"),
        ("2-й квартал и на 3-м месте", "второй квартал и на третьем месте"),
        ("в 18:30", "в восемнадцать тридцать"),
    ],
)
def test_years_dates_ordinals_and_times(text: str, expected: str) -> None:
    assert russian_numbers_to_words(text) == expected


def test_keeps_sentence_punctuation_and_spacing() -> None:
    assert russian_numbers_to_words("Цена выросла на 300 долларов. Далее") == "Цена выросла на триста долларов. Далее"
